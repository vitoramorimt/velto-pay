export function createProductSlug(value: string): string {
  const slug = value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .replace(/-{2,}/g, "-");

  return slug || "produto";
}

export function appendSlugSuffix(slug: string, suffix: number): string {
  return `${slug}-${suffix}`;
}
